// ---------------------------------------------------------------------------
// Build thesaurus
// ---------------------------------------------------------------------------

async function buildThesaurus(): Promise<void> {
  console.log(`Generating thesaurus for ${COMMON_WORDS.length} words...`);

  const wp = new WordPOS();
  const thesaurus: Record<string, string[]> = {};

  let done = 0;
  let found = 0;

  for (const word of COMMON_WORDS) {
    try {
      const synsets = await wp.lookup(word);
      const synonyms = new Set<string>();

      for (const synset of synsets) {
        if (synset.synonyms && Array.isArray(synset.synonyms)) {
          for (const syn of synset.synonyms) {
            const normalized = syn.toLowerCase().replace(/_/g, " ").trim();
            if (normalized !== word && normalized.length > 1) {
              synonyms.add(normalized);
            }
          }
        }
      }

      if (synonyms.size > 0) {
        thesaurus[word] = [...synonyms].slice(0, 12); // max 12 per word
        found++;
      }
    } catch {
      // Word not in WordNet — skip
    }

    done++;
    if (done % 200 === 0) {
      console.log(`  ${done}/${COMMON_WORDS.length} (${found} with synonyms)`);
    }
  }

  // Write output
  const outputDir = path.join(os.homedir(), ".chrollo");
  fs.mkdirSync(outputDir, { recursive: true });
  const outputPath = path.join(outputDir, "thesaurus.json");
  fs.writeFileSync(outputPath, JSON.stringify(thesaurus), "utf-8");

  const sizeKB = Math.round(fs.statSync(outputPath).size / 1024);
  console.log(`\nDone! ${Object.keys(thesaurus).length} words with synonyms`);
  console.log(`Output: ${outputPath} (${sizeKB}KB)`);
}

buildThesaurus().catch(console.error);
